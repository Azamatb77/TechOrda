"""
Генератор синтетических данных для E-commerce аналитики.
Создаёт два CSV файла: customers.csv и orders.csv
"""

import pandas as pd
import numpy as np
import os
from datetime import datetime, timedelta

# Фиксируем случайное зерно для воспроизводимости
np.random.seed(42)

# ============================================================
# Параметры генерации
# ============================================================
КОЛИЧЕСТВО_КЛИЕНТОВ = 500
КОЛИЧЕСТВО_ЗАКАЗОВ = 5000

# Каналы привлечения и их веса
КАНАЛЫ_ПРИВЛЕЧЕНИЯ = ['органический', 'платная_реклама', 'реферальный', 'email', 'социальные_сети']
ВЕСА_КАНАЛОВ = [0.30, 0.25, 0.20, 0.15, 0.10]

# Категории товаров
КАТЕГОРИИ = ['электроника', 'одежда', 'продукты', 'спорт', 'дом_и_сад', 'книги', 'красота']
ВЕСА_КАТЕГОРИЙ = [0.20, 0.18, 0.15, 0.14, 0.13, 0.11, 0.09]

# Статусы заказов
СТАТУСЫ = ['выполнен', 'выполнен', 'выполнен', 'выполнен', 'отменён', 'возврат']
# (~67% выполнен, ~17% отменён, ~17% возврат)

# Диапазон дат (последние 12 месяцев)
ДАТА_КОНЦА = datetime(2024, 12, 31)
ДАТА_НАЧАЛА = datetime(2024, 1, 1)

# ============================================================
# ШАГ 1: Генерация клиентов
# ============================================================
print("Генерация данных клиентов...")

# Случайные даты регистрации
дни_регистрации = np.random.randint(0, (ДАТА_КОНЦА - ДАТА_НАЧАЛА).days, КОЛИЧЕСТВО_КЛИЕНТОВ)
даты_регистрации = [ДАТА_НАЧАЛА + timedelta(days=int(d)) for d in дни_регистрации]

# CAC зависит от канала привлечения
каналы = np.random.choice(КАНАЛЫ_ПРИВЛЕЧЕНИЯ, size=КОЛИЧЕСТВО_КЛИЕНТОВ, p=ВЕСА_КАНАЛОВ)

# Стоимость привлечения (CAC) по каналам
cac_по_каналам = {
    'органический': (200, 50),      # среднее, стд
    'платная_реклама': (800, 200),
    'реферальный': (350, 80),
    'email': (150, 40),
    'социальные_сети': (500, 120),
}

cac_значения = []
for канал in каналы:
    среднее, стд = cac_по_каналам[канал]
    значение = max(50, np.random.normal(среднее, стд))
    cac_значения.append(round(значение, 2))

df_клиенты = pd.DataFrame({
    'customer_id': [f'C{str(i).zfill(4)}' for i in range(1, КОЛИЧЕСТВО_КЛИЕНТОВ + 1)],
    'канал_привлечения': каналы,
    'дата_регистрации': [d.strftime('%Y-%m-%d') for d in даты_регистрации],
    'cac': cac_значения,
})

print(f"  Создано клиентов: {len(df_клиенты)}")

# ============================================================
# ШАГ 2: Генерация заказов
# ============================================================
print("Генерация данных заказов...")

# Случайные customer_id из существующих клиентов
# Некоторые клиенты делают больше заказов (степенное распределение)
вес_клиентов = np.random.power(0.5, КОЛИЧЕСТВО_КЛИЕНТОВ)
вес_клиентов = вес_клиентов / вес_клиентов.sum()

клиент_ids = np.random.choice(df_клиенты['customer_id'].values, size=КОЛИЧЕСТВО_ЗАКАЗОВ, p=вес_клиентов)

# Даты заказов — равномерно за год
дни_заказов = np.random.randint(0, (ДАТА_КОНЦА - ДАТА_НАЧАЛА).days, КОЛИЧЕСТВО_ЗАКАЗОВ)
даты_заказов = [ДАТА_НАЧАЛА + timedelta(days=int(d)) for d in дни_заказов]

# Суммы заказов — логнормальное распределение (реалистично для e-commerce)
суммы_заказов = np.random.lognormal(mean=6.5, sigma=0.8, size=КОЛИЧЕСТВО_ЗАКАЗОВ)
суммы_заказов = np.clip(суммы_заказов, 100, 50000)
суммы_заказов = np.round(суммы_заказов, 2)

# Категории и статусы
категории_заказов = np.random.choice(КАТЕГОРИИ, size=КОЛИЧЕСТВО_ЗАКАЗОВ, p=ВЕСА_КАТЕГОРИЙ)
статусы_заказов = np.random.choice(СТАТУСЫ, size=КОЛИЧЕСТВО_ЗАКАЗОВ)

df_заказы = pd.DataFrame({
    'order_id': [f'O{str(i).zfill(5)}' for i in range(1, КОЛИЧЕСТВО_ЗАКАЗОВ + 1)],
    'customer_id': клиент_ids,
    'дата_заказа': [d.strftime('%Y-%m-%d') for d in даты_заказов],
    'сумма_заказа': суммы_заказов,
    'категория': категории_заказов,
    'статус': статусы_заказов,
})

print(f"  Создано заказов: {len(df_заказы)}")

# ============================================================
# ШАГ 3: Сохранение CSV файлов
# ============================================================
os.makedirs('data', exist_ok=True)

путь_клиенты = 'data/customers.csv'
путь_заказы = 'data/orders.csv'

df_клиенты.to_csv(путь_клиенты, index=False, encoding='utf-8')
df_заказы.to_csv(путь_заказы, index=False, encoding='utf-8')

print(f"\nФайлы успешно сохранены:")
print(f"  {путь_клиенты} — {os.path.getsize(путь_клиенты):,} байт")
print(f"  {путь_заказы} — {os.path.getsize(путь_заказы):,} байт")

# Краткая статистика
print("\nСтатистика клиентов:")
print(f"  Каналы привлечения: {df_клиенты['канал_привлечения'].value_counts().to_dict()}")
print(f"  Средний CAC: {df_клиенты['cac'].mean():.2f} ₸")

print("\nСтатистика заказов:")
print(f"  Статусы: {df_заказы['статус'].value_counts().to_dict()}")
print(f"  Средняя сумма заказа: {df_заказы['сумма_заказа'].mean():.2f} ₸")
print(f"  Категории: {df_заказы['категория'].value_counts().to_dict()}")
