"""
Генератор синтетических данных для финтех-аналитики.
Создаёт CSV файлы с данными клиентов и транзакций.
"""

import numpy as np
import pandas as pd
import os

# Фиксируем случайное зерно для воспроизводимости
np.random.seed(42)

# ─────────────────────────────────────────
# Параметры генерации
# ─────────────────────────────────────────
КОЛИЧЕСТВО_КЛИЕНТОВ = 3000
МЕСЯЦЕВ = 12

# Папка для сохранения данных
os.makedirs('data', exist_ok=True)

# ─────────────────────────────────────────
# 1. Генерация таблицы клиентов
# ─────────────────────────────────────────
print("Генерируем данные клиентов...")

возраст = np.random.randint(18, 75, КОЛИЧЕСТВО_КЛИЕНТОВ)

# Доход зависит от возраста (более опытные зарабатывают больше)
базовый_доход = 30000 + (возраст - 18) * 800
доход = (базовый_доход + np.random.normal(0, 15000, КОЛИЧЕСТВО_КЛИЕНТОВ)).clip(15000, 250000).astype(int)

образование_варианты = ['Среднее', 'Среднее специальное', 'Высшее', 'Магистратура', 'Аспирантура']
образование_вероятности = [0.10, 0.20, 0.45, 0.20, 0.05]
образование = np.random.choice(образование_варианты, КОЛИЧЕСТВО_КЛИЕНТОВ, p=образование_вероятности)

семейное_положение_варианты = ['Холост/Не замужем', 'Женат/Замужем', 'Разведён/Разведена', 'Вдовец/Вдова']
семейное_положение_вероятности = [0.35, 0.45, 0.15, 0.05]
семейное_положение = np.random.choice(семейное_положение_варианты, КОЛИЧЕСТВО_КЛИЕНТОВ, p=семейное_положение_вероятности)

месяцев_на_обслуживании = np.random.randint(1, 121, КОЛИЧЕСТВО_КЛИЕНТОВ)

# Кредитный лимит зависит от дохода
кредитный_лимит = (доход * np.random.uniform(0.3, 0.8, КОЛИЧЕСТВО_КЛИЕНТОВ)).astype(int)
# Округляем до тысяч
кредитный_лимит = (кредитный_лимит // 1000) * 1000
кредитный_лимит = кредитный_лимит.clip(5000, 150000)

клиенты = pd.DataFrame({
    'client_id': range(1, КОЛИЧЕСТВО_КЛИЕНТОВ + 1),
    'возраст': возраст,
    'доход': доход,
    'образование': образование,
    'семейное_положение': семейное_положение,
    'месяцев_на_обслуживании': месяцев_на_обслуживании,
    'кредитный_лимит': кредитный_лимит,
})

клиенты.to_csv('data/clients.csv', index=False, encoding='utf-8')
print(f"  Сохранено {len(клиенты)} клиентов → data/clients.csv")

# ─────────────────────────────────────────
# 2. Генерация таблицы транзакций
# ─────────────────────────────────────────
print("Генерируем транзакции за 12 месяцев...")

категории = ['Продукты', 'Рестораны', 'Транспорт', 'Развлечения', 'Путешествия',
             'Одежда', 'Здоровье', 'Образование', 'Коммунальные услуги', 'Прочее']

# Вероятности категорий
вероятности_категорий = [0.22, 0.15, 0.12, 0.10, 0.13, 0.08, 0.07, 0.05, 0.05, 0.03]

транзакции_список = []
transaction_id = 1

for _, клиент in клиенты.iterrows():
    # Количество транзакций в месяц зависит от дохода
    базовые_транзакции = int(3 + клиент['доход'] / 20000)

    for месяц in range(1, МЕСЯЦЕВ + 1):
        # Сезонный коэффициент (Q4 — праздничные траты)
        сезонный_коэф = 1.0
        if месяц in [11, 12]:
            сезонный_коэф = 1.35
        elif месяц in [6, 7]:
            сезонный_коэф = 1.15

        кол_транзакций = max(1, int(np.random.poisson(базовые_транзакции * сезонный_коэф)))

        for _ in range(кол_транзакций):
            категория = np.random.choice(категории, p=вероятности_категорий)

            # Средний чек зависит от категории и дохода
            базовые_суммы = {
                'Продукты': 3500, 'Рестораны': 4500, 'Транспорт': 2000,
                'Развлечения': 3000, 'Путешествия': 25000, 'Одежда': 8000,
                'Здоровье': 5000, 'Образование': 12000, 'Коммунальные услуги': 6000,
                'Прочее': 4000
            }

            доходный_коэф = 0.5 + (клиент['доход'] / 100000)
            базовая_сумма = базовые_суммы[категория] * доходный_коэф
            сумма = max(100, np.random.lognormal(np.log(базовая_сумма), 0.5))
            сумма = round(сумма, 2)

            транзакции_список.append({
                'transaction_id': transaction_id,
                'client_id': клиент['client_id'],
                'месяц': месяц,
                'сумма': сумма,
                'категория': категория,
            })
            transaction_id += 1

транзакции = pd.DataFrame(транзакции_список)
транзакции.to_csv('data/transactions.csv', index=False, encoding='utf-8')
print(f"  Сохранено {len(транзакции)} транзакций → data/transactions.csv")

# ─────────────────────────────────────────
# Итоговая статистика
# ─────────────────────────────────────────
print("\n=== Итоговая статистика ===")
print(f"Клиентов:      {len(клиенты):,}")
print(f"Транзакций:    {len(транзакции):,}")
print(f"Средний доход: {клиенты['доход'].mean():,.0f} тг")
print(f"Средний лимит: {клиенты['кредитный_лимит'].mean():,.0f} тг")
print(f"Средняя сумма транзакции: {транзакции['сумма'].mean():,.2f} тг")
print("\nДанные успешно сгенерированы!")
