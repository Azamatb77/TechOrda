"""
Скрипт генерации синтетических данных маркетинговых кампаний.
Создаёт файл data/campaigns.csv с ~200 записями.
"""

import numpy as np
import pandas as pd
import os

# Фиксируем случайный seed для воспроизводимости
np.random.seed(42)

# Параметры генерации
КОЛИЧЕСТВО_КАМПАНИЙ = 200
КАНАЛЫ = ['Google Ads', 'Facebook', 'Instagram', 'Email', 'TikTok']

# Параметры каналов: (средний_бюджет, std_бюджета, roi_коэффициент, ctr_базовый, cvr_базовый)
ПАРАМЕТРЫ_КАНАЛОВ = {
    'Google Ads':  {'бюджет_среднее': 15000, 'бюджет_std': 5000,  'roi': 1.25, 'ctr': 0.045, 'cvr': 0.10},
    'Facebook':    {'бюджет_среднее': 12000, 'бюджет_std': 4000,  'roi': 1.05, 'ctr': 0.038, 'cvr': 0.08},
    'Instagram':   {'бюджет_среднее': 10000, 'бюджет_std': 3500,  'roi': 1.10, 'ctr': 0.042, 'cvr': 0.09},
    'Email':       {'бюджет_среднее': 5000,  'бюджет_std': 1500,  'roi': 1.45, 'ctr': 0.055, 'cvr': 0.14},
    'TikTok':      {'бюджет_среднее': 8000,  'бюджет_std': 3000,  'roi': 0.95, 'ctr': 0.050, 'cvr': 0.07},
}

# Генерируем список каналов (равномерное распределение)
каналы_список = np.random.choice(КАНАЛЫ, size=КОЛИЧЕСТВО_КАМПАНИЙ)

# Генерируем даты начала кампаний (в течение 2024 года)
дата_начала = pd.date_range(start='2024-01-01', end='2024-12-31', periods=КОЛИЧЕСТВО_КАМПАНИЙ)
дата_начала = np.random.choice(дата_начала, size=КОЛИЧЕСТВО_КАМПАНИЙ, replace=False)
дата_начала = np.sort(дата_начала)

записи = []

for i, (канал, дата) in enumerate(zip(каналы_список, дата_начала)):
    парам = ПАРАМЕТРЫ_КАНАЛОВ[канал]

    # Бюджет кампании
    бюджет = max(1000, np.random.normal(парам['бюджет_среднее'], парам['бюджет_std']))

    # Показы зависят от бюджета (CPM ~5-15 руб за 1000 показов)
    cpm = np.random.uniform(5, 15)
    показы = int(бюджет / cpm * 1000)

    # Клики через CTR с шумом
    ctr = max(0.005, np.random.normal(парам['ctr'], 0.01))
    клики = int(показы * ctr)

    # Конверсии через CVR с шумом
    cvr = max(0.01, np.random.normal(парам['cvr'], 0.02))
    конверсии = int(клики * cvr)

    # Выручка = бюджет * ROI с случайным отклонением
    roi_factor = np.random.normal(парам['roi'], 0.15)
    выручка = round(бюджет * roi_factor, 2)

    # Иногда добавляем аномалии (5% случаев)
    if np.random.random() < 0.05:
        выручка *= np.random.uniform(1.5, 2.5)

    записи.append({
        'campaign_id': f'CAMP_{i+1:04d}',
        'канал': канал,
        'бюджет': round(бюджет, 2),
        'показы': показы,
        'клики': клики,
        'конверсии': конверсии,
        'выручка': round(выручка, 2),
        'дата_начала': pd.Timestamp(дата).strftime('%Y-%m-%d'),
    })

# Создаём DataFrame
df = pd.DataFrame(записи)

# Проверяем директорию
os.makedirs('data', exist_ok=True)

# Сохраняем CSV
df.to_csv('data/campaigns.csv', index=False, encoding='utf-8')

print(f"✓ Файл data/campaigns.csv успешно создан!")
print(f"  Количество кампаний: {len(df)}")
print(f"  Столбцы: {list(df.columns)}")
print(f"\nПервые 5 строк:")
print(df.head())
print(f"\nРаспределение по каналам:")
print(df['канал'].value_counts())
